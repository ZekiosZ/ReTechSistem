CREATE TABLE T_USUARIO (
    ID_USUARIO NUMBER(10) NOT NULL,
    NOME_COMPLETO VARCHAR2(100) NOT NULL,
    CPF VARCHAR2(11) NOT NULL,
    PONTOS_SALDO NUMBER(6) DEFAULT 0 NOT NULL,
    DATA_CADASTRO DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT T_USUARIO_PK PRIMARY KEY (ID_USUARIO),
    CONSTRAINT T_USUARIO_SALDO_CK CHECK (PONTOS_SALDO >= 0)
);
CREATE INDEX IDX_T_USUARIO_CPF ON T_USUARIO(CPF);
CREATE SEQUENCE SEQ_T_USUARIO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE T_CATEGORIA_ELETRO (
    ID_CATEGORIA NUMBER(10) NOT NULL,
    NOME_CATEGORIA VARCHAR2(50) NOT NULL,
    PONTOS_POR_UNIDADE NUMBER(4) NOT NULL,
    CONSTRAINT T_CATEGORIA_ELETRO_PK PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT T_CATEGORIA_ELETRO_PONTOS_CK CHECK (PONTOS_POR_UNIDADE >= 0)
);
CREATE SEQUENCE SEQ_T_CATEGORIA_ELETRO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE T_MAQUINA (
    ID_MAQUINA NUMBER(10) NOT NULL,
    BAIRRO_LOCALIZACAO VARCHAR2(100) NOT NULL,
    CEP VARCHAR2(8) NOT NULL,
    STATUS_OPERACAO VARCHAR2(20) NOT NULL,
    CONSTRAINT T_MAQUINA_PK PRIMARY KEY (ID_MAQUINA)
);
CREATE SEQUENCE SEQ_T_MAQUINA START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE T_INSTITUICAO (
    ID_INSTITUICAO NUMBER(10) NOT NULL,
    NOME_FANTASIA VARCHAR2(100) NOT NULL,
    CNPJ VARCHAR2(14) NOT NULL,
    TIPO_PARCEIRO VARCHAR2(30) NOT NULL,
    CONSTRAINT T_INSTITUICAO_PK PRIMARY KEY (ID_INSTITUICAO)
);
CREATE INDEX IDX_T_INSTITUICAO_CNPJ ON T_INSTITUICAO(CNPJ);
CREATE SEQUENCE SEQ_T_INSTITUICAO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE T_DESCARTE (
    ID_DESCARTE NUMBER(10) NOT NULL,
    ID_USUARIO NUMBER(10) NOT NULL,
    ID_MAQUINA NUMBER(10) NOT NULL,
    ID_CATEGORIA NUMBER(10) NOT NULL,
    ID_INSTITUICAO NUMBER(10) NOT NULL,
    DATA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
    QUANTIDADE NUMBER(3) NOT NULL,
    PONTOS_GERADOS NUMBER(6) NOT NULL,
    CONSTRAINT T_DESCARTE_PK PRIMARY KEY (ID_DESCARTE),
    CONSTRAINT FK_DESCARTE_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_USUARIO(ID_USUARIO),
    CONSTRAINT FK_DESCARTE_MAQUINA FOREIGN KEY (ID_MAQUINA) REFERENCES T_MAQUINA(ID_MAQUINA),
    CONSTRAINT FK_DESCARTE_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES T_CATEGORIA_ELETRO(ID_CATEGORIA),
    CONSTRAINT FK_DESCARTE_INSTITUICAO FOREIGN KEY (ID_INSTITUICAO) REFERENCES T_INSTITUICAO(ID_INSTITUICAO),
    CONSTRAINT T_DESCARTE_QTD_CK CHECK (QUANTIDADE BETWEEN 1 AND 999),
    CONSTRAINT T_DESCARTE_PONTOS_CK CHECK (PONTOS_GERADOS >= 0)
);
CREATE INDEX IDX_DESCARTE_USUARIO ON T_DESCARTE(ID_USUARIO);
CREATE INDEX IDX_DESCARTE_MAQUINA ON T_DESCARTE(ID_MAQUINA);
CREATE INDEX IDX_DESCARTE_CATEGORIA ON T_DESCARTE(ID_CATEGORIA);
CREATE INDEX IDX_DESCARTE_INSTITUICAO ON T_DESCARTE(ID_INSTITUICAO);
CREATE SEQUENCE SEQ_T_DESCARTE START WITH 1 INCREMENT BY 1 NOCACHE;
